-- 002: station-scoped incremental change feed and receiver sessions.
-- The ORM creates these tables at startup; this file records the equivalent DDL.

ALTER TABLE public.arrivals ADD COLUMN IF NOT EXISTS dataset character varying(40) NOT NULL DEFAULT 'live';

CREATE TABLE IF NOT EXISTS public.arrival_changes (
    id bigserial PRIMARY KEY,
    arrival_id integer NOT NULL,
    code character varying(60) NOT NULL,
    revision integer NOT NULL,
    old_station character varying(30),
    new_station character varying(30) NOT NULL,
    payload json,
    changed_at character varying(40),
    actor character varying(100) DEFAULT '',
    dataset character varying(40) NOT NULL DEFAULT 'live',
    CONSTRAINT uq_change_arrival_revision UNIQUE (arrival_id, revision)
);
CREATE INDEX IF NOT EXISTS ix_change_station_seq ON public.arrival_changes (new_station, id);
CREATE INDEX IF NOT EXISTS ix_change_old_station_seq ON public.arrival_changes (old_station, id);

CREATE TABLE IF NOT EXISTS public.sync_subscriptions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL UNIQUE,
    station character varying(30) NOT NULL,
    receiver character varying(80) DEFAULT '',
    dataset character varying(40) NOT NULL DEFAULT 'live',
    enabled boolean,
    token_hash character varying(64) NOT NULL UNIQUE,
    generation integer NOT NULL DEFAULT 1,
    cursor_seq bigint NOT NULL DEFAULT 0,
    bootstrapped boolean NOT NULL DEFAULT false,
    bootstrap_to bigint,
    created_at character varying(40),
    last_pull_at character varying(40),
    last_confirm_at character varying(40),
    last_report_at character varying(40)
);

CREATE TABLE IF NOT EXISTS public.sync_batches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id integer NOT NULL REFERENCES public.sync_subscriptions(id),
    kind character varying(20) NOT NULL,
    seq_from bigint NOT NULL,
    seq_to bigint NOT NULL,
    events json,
    checksum character varying(64),
    status character varying(20) DEFAULT 'pending',
    created_at character varying(40),
    confirmed_at character varying(40)
);
CREATE INDEX IF NOT EXISTS ix_sync_batch_sub_status ON public.sync_batches (subscription_id, status);

CREATE TABLE IF NOT EXISTS public.sync_reports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id integer NOT NULL REFERENCES public.sync_subscriptions(id),
    generation integer NOT NULL DEFAULT 1,
    applied_seq bigint NOT NULL,
    confirmed_seq bigint NOT NULL,
    record_count integer DEFAULT 0,
    records json,
    note text DEFAULT '',
    reported_at character varying(40)
);
CREATE INDEX IF NOT EXISTS ix_sync_report_sub_id ON public.sync_reports (subscription_id, id);

CREATE TABLE IF NOT EXISTS public.sync_drill_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor character varying(100),
    created_at character varying(40),
    status character varying(20),
    summary json
);
